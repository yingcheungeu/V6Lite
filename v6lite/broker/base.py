"""Broker port: the only surface the engine uses to touch a broker.

Adapters must keep exactly ONE physical order-placement call site
(_place_order). LMT orders and typed protective STP are the only contracts; there is no MKT
method to call by mistake.
"""

from __future__ import annotations

from datetime import datetime
from typing import Protocol

from v6lite.models import (
    Bar, BrokerAck, BrokerEvent, BrokerPosition, FillEvent, FundsSnapshot, OpenOrder, OrderRequest,
    ProtectionRequest, Quote, CompletedOrdersSnapshot,
)


class BrokerError(RuntimeError):
    """Raised for broker failures. `maybe_sent=True` means the order may have
    reached the broker and must be treated as UNKNOWN, never as failed."""

    def __init__(self, message: str, *, maybe_sent: bool = False):
        super().__init__(message)
        self.maybe_sent = maybe_sent


class BrokerPort(Protocol):
    def connect(self) -> None: ...
    def disconnect(self) -> None: ...
    def is_connected(self) -> bool: ...
    def is_synchronized(self) -> bool:
        """API ready and registered SDK startup queries completed; not broker proof."""
        ...
    def pump(self, seconds: float) -> None: ...
    def gateway_heartbeat_request(self) -> None:
        """Send a read-only current-time request without waiting for its reply."""
        ...
    def gateway_heartbeat_reply_count(self) -> int:
        """Monotone count of current-time replies seen on this broker instance."""
        ...
    def gateway_heartbeat_replies(self) -> tuple[datetime, ...]:
        """UTC server times in currentTime callback order, append-only."""
        ...
    def managed_accounts(self) -> list[str]: ...
    def net_liquidation(self) -> float | None: ...
    def available_funds(self) -> FundsSnapshot:
        """AvailableFunds with change time, stream freshness and readiness."""
        ...
    def refresh_funds(self) -> None:
        """Nonblocking funds download; sending cannot renew a funds timestamp."""
        ...
    def worst_case_seconds(self, kind: str) -> float:
        """Upper bound for one blocking call of `kind` ('history', 'vix',
        'query'). The engine budgets exit checks around these bounds."""
        ...
    def positions(self) -> list[BrokerPosition]:
        """Streamed position cache (fast, may lag)."""
        ...
    def positions_fresh(self) -> list[BrokerPosition]:
        """Fresh server query (blocking, cost 'query'); raises on failure."""
        ...
    def open_orders(self) -> list[OpenOrder]:
        """FRESH server-side list of this account's V6-Lite working orders
        (never a local cache). Must raise if the answer is not complete."""
        ...
    def completed_orders(self) -> CompletedOrdersSnapshot:
        """Fresh own-request/End snapshot including TWS orders; never startup/cache."""
        ...
    def previous_close(self, symbol: str) -> float | None:
        """Close of the last completed session before today (ET)."""
        ...
    def qualify(self, symbol: str) -> int: ...
    def subscribe_quotes(self, symbols: list[str]) -> None: ...
    def quote(self, symbol: str) -> Quote | None: ...
    def daily_bars(self, symbol: str, days: int) -> list[Bar]: ...
    def vix_close(self) -> float | None: ...
    def submit_limit(self, req: OrderRequest) -> BrokerAck: ...
    def submit_stop(self, req: ProtectionRequest) -> BrokerAck: ...
    def modify_protection(self, req: ProtectionRequest) -> BrokerAck: ...
    def cancel(self, intent_id: str, *, expected_order_id: int | None = None,
               expected_perm_id: int | None = None, expected_con_id: int | None = None,
               allow_lookup: bool = True) -> None: ...
    def executions_today(self) -> list[FillEvent]: ...
    def account_executions_today(self) -> list[FillEvent]:
        """Read-only execution evidence for the configured account across clients.

        Returned rows are not ownership claims and must not be booked as fills.
        """
        ...
    def account_executions_today_scoped(self) -> list[FillEvent]:
        """Optional explicit-UTC-day visible query; only its result scope can prove day membership."""
        ...
    def drain_events(self) -> list[BrokerEvent]: ...
